#[cfg(test)]
mod tests {
    use super::*;

    /// The licence list matches Cargo.lock; if this fails, run tools/gen_licenses.py.
    #[test]
    fn third_party_list_is_current() {
        let lock = include_str!("../../../Cargo.lock");
        let mut locked = std::collections::HashSet::new();
        let mut name = "";
        for line in lock.lines() {
            if let Some(n) = line.strip_prefix("name = ") {
                name = n.trim_matches('"');
            } else if let Some(v) = line.strip_prefix("version = ") {
                locked.insert((name, v.trim_matches('"')));
            }
        }
        let lic = licences();
        assert!(lic.crates.len() > 100);
        for (name, version, expr, _, own) in &lic.crates {
            assert!(locked.contains(&(name.as_str(), version.as_str())), "{name} {version} is not in Cargo.lock");
            // every crate has a licence text: its own, or a standard one for each identifier
            let ids = licence_ids(expr);
            assert!(!own.is_empty() || (!ids.is_empty() && ids.iter().all(|i| lic.spdx.contains_key(*i))), "{name} has no licence text");
            assert!(own.iter().all(|i| *i < lic.texts.len()));
        }
        // every direct dependency is listed
        let manifest = include_str!("../Cargo.toml");
        let deps = manifest.split("[dependencies]").nth(1).unwrap().split("\n[").next().unwrap();
        for line in deps.lines().filter(|l| l.contains('=') && !l.trim_start().starts_with("dd-")) {
            let dep = line.split(['=', '.']).next().unwrap().trim();
            assert!(lic.crates.iter().any(|c| c.0 == dep), "{dep} missing from the licence list");
        }
    }

    #[test]
    fn licence_texts_are_bundled() {
        assert!(APP_LICENCE.starts_with("MIT License"));
        assert!(GENERALUSER_LICENCE.contains("GeneralUser GS"));
        assert!(ELECTRONIC_LICENCE.contains("MIT License"));
        assert!(CC0_TEXT.contains("CC0"));
        assert!(RAIN_CREDITS.contains("CC0"));
        assert!(LIGHTCRAFT_TEXT.contains("LightCraft contributors"));
        for (name, _, text) in TYPEFACES {
            assert!(text.to_uppercase().contains("OPEN FONT LICENSE"), "{name}");
        }
        assert!(licences().spdx.get("Apache-2.0").is_some_and(|t| t.contains("Apache License")));
        assert!(eframe::icon_data::from_png_bytes(ICON_PNG).is_ok());
        assert!(!COMMIT.is_empty());
    }
}
